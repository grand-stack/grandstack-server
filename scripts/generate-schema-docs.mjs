#!/usr/bin/env node
// Generates docs/schema-reference.md from schema/schema.graphql.
// Usage: node scripts/generate-schema-docs.mjs [--check]
// With --check it exits 1 if the committed file differs from what would be generated (used in CI).
import { readFileSync, writeFileSync } from "node:fs";
import { parse, print, Kind } from "graphql";

const SCHEMA = "schema/schema.graphql";
const OUT = "docs/schema-reference.md";

const doc = parse(readFileSync(SCHEMA, "utf8"));

const args = (directive) =>
  Object.fromEntries((directive.arguments ?? []).map((a) => [a.name.value, a.value.kind === Kind.STRING ? a.value.value : print(a.value)]));

const oneLine = (text = "") => text.replace(/\s+/g, " ").trim().replace(/\|/g, "\\|");

function describeDirectives(field) {
  const notes = [];
  for (const d of field.directives ?? []) {
    const a = args(d);
    if (d.name.value === "relationship") {
      notes.push(`relationship \`${a.type}\` (${a.direction})${a.properties ? `, properties \`${a.properties}\`` : ""}`);
    } else if (d.name.value === "cypher") {
      notes.push("computed by a `@cypher` statement (see below)");
    } else {
      notes.push(`@${d.name.value}`);
    }
  }
  return notes.join("; ");
}

const lines = [];
lines.push("# Schema reference", "");
lines.push(`<!-- GENERATED by scripts/generate-schema-docs.mjs from ${SCHEMA}. Do not edit; run \`npm run docs:schema\`. -->`, "");
lines.push(
  "Every type and field below comes from `schema/schema.graphql`. `@neo4j/graphql` also generates queries, mutations, filters and sort inputs for each `@node` type (for example `movies`, `moviesConnection`, `createMovies`, `updateMovies`, `deleteMovies`); those are not listed here. See [mutations](mutations.md) and the live schema at `/graphql` for the generated parts.",
  "",
);

const cypherFields = [];
for (const def of doc.definitions) {
  if (def.kind !== Kind.OBJECT_TYPE_DEFINITION) continue;
  const name = def.name.value;
  const kind = (def.directives ?? []).some((d) => d.name.value === "node")
    ? "node type (stored in Neo4j)"
    : (def.directives ?? []).some((d) => d.name.value === "relationshipProperties")
      ? "relationship properties"
      : "plain object type";
  lines.push(`## ${name}`, "", `*${kind}.* ${oneLine(def.description?.value)}`, "");
  lines.push("| Field | Type | Description |", "| --- | --- | --- |");
  for (const f of def.fields ?? []) {
    const fargs = (f.arguments ?? []).map((a) => `${a.name.value}: ${print(a.type)}${a.defaultValue ? ` = ${print(a.defaultValue)}` : ""}`);
    const sig = fargs.length ? `\`${f.name.value}(${fargs.join(", ")})\`` : `\`${f.name.value}\``;
    const notes = describeDirectives(f);
    const argDocs = (f.arguments ?? []).filter((a) => a.description).map((a) => ` Argument \`${a.name.value}\`: ${oneLine(a.description.value)}`).join("");
    lines.push(`| ${sig} | \`${print(f.type)}\` | ${oneLine(f.description?.value)}${argDocs}${notes ? ` *(${notes})*` : ""} |`);
    const cypher = (f.directives ?? []).find((d) => d.name.value === "cypher");
    if (cypher) cypherFields.push({ type: name, field: f.name.value, statement: args(cypher).statement });
  }
  lines.push("");
}

if (cypherFields.length) {
  lines.push("## Computed fields (`@cypher`)", "", "These fields run a Cypher statement on request, so they always reflect the current graph.", "");
  for (const c of cypherFields) {
    lines.push(`### \`${c.type}.${c.field}\``, "", "```cypher", c.statement.trim().replace(/^\s+/gm, ""), "```", "");
  }
}

const output = lines.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd() + "\n";

if (process.argv.includes("--check")) {
  let current = "";
  try { current = readFileSync(OUT, "utf8"); } catch { /* missing file counts as out of date */ }
  if (current !== output) {
    console.error(`${OUT} is out of date. Run: npm run docs:schema`);
    process.exit(1);
  }
  console.log(`${OUT} is up to date`);
} else {
  writeFileSync(OUT, output);
  console.log(`Wrote ${OUT}`);
}
